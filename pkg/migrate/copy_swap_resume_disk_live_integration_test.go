// errStopAtCatchUp is what the host's hook stops the first run with.
var errStopAtCatchUp = errors.New("the host stops the run at its catch-up save")

const (
	// resumedRunCeiling is the raised ceiling the resume runs under, as an
	// operator raises it after a wal-retained stop: twice the default the
	// first run runs under.
	resumedRunCeiling int64 = 2 << 30
	// resumeDiskMargin is the slack the free-disk figure carries above the
	// remaining need, for a page the source gains between the test's
	// reading and the preflight's. It is far below the shadow's size and
	// the slot's retained WAL, so neither discount alone admits the
	// resume.
	resumeDiskMargin int64 = 64 << 10
)

// A live run stopped partway already holds its shadow and its slot's WAL
// on the volume, and the free space an operator measures before resuming
// excludes both. The resume's preflight discounts both, read from the
// server, and asks only for what is left to grow: here a free-disk figure
// that covers the rest of the shadow's headroom and the raised ceiling
// less the WAL the slot already retains admits the resume, which runs to
// the swap. A run that does not resume — the same statement started over
// with the restart acknowledgement, whose discard would free what the
// stopped run holds — is checked as a fresh run, and the same figure is
// refused copy-and-swap-disk-headroom with the stopped run left as it was.
//
// The table is the live fixture's workload table:
//
//	CREATE TABLE workload (
//	    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
//	    uniq integer NOT NULL UNIQUE,
//	    amount numeric(12,2) NOT NULL,
//	    label text NOT NULL,
//	    blob text,               -- STORAGE EXTERNAL, always out of line
//	    updated_at timestamptz NOT NULL DEFAULT now()
//	);
//
// and the statement widens amount's scale, which rewrites every value and
// so routes to copy-and-swap.
func TestRunCopySwapResumeIsAskedOnlyForTheDiskLeftToGrow(t *testing.T) {
	shape := testutil.WorkloadShape{}
	f := newLiveFixture(t, shape)
	const alter = `ALTER TABLE %s ALTER COLUMN amount TYPE numeric(14,4)`
	st := parseOne(t, fmt.Sprintf(alter, f.table.Qualified()))
	schema, table := f.table.Schema, f.table.Table
	// Vacuumed up front, so autovacuum adds no visibility or free-space
	// map to the source between the test's size reading and the
	// preflight's.
	f.exec(t, `VACUUM `+f.table.Qualified())

	// The first run stops when the copy is done and the catch-up phase is
	// saved: the shadow holds every row, and the slot stays. It runs under
	// the default ceiling, which the copy's own WAL stays well inside.
	stopped := f.options()
	stopped.CopySwap.OnCheckpoint = func(_ context.Context, cp checkpoint.Checkpoint) error {
		if cp.Phase == checkpoint.PhaseCatchingUp {
			return errStopAtCatchUp
		}
		return nil
	}
	v, err := migrate.Run(t.Context(), f.pool, st, stopped)
	require.ErrorIs(t, err, errStopAtCatchUp)
	require.Equal(t, verdict.OutcomeFailed, v.Outcome, "%s: %s", v.Reason, v.Detail)
	row := f.inspectRow(t)
	require.Equal(t, checkpoint.PhaseCatchingUp, row.Phase)
	require.NotEmpty(t, row.SlotName)

	// While the run is stopped the source's cluster keeps writing WAL,
	// which the slot retains.
	f.exec(t, `
		CREATE TABLE `+pgx.Identifier{schema, "wal_filler"}.Sanitize()+` (
		    id integer PRIMARY KEY,
		    payload text NOT NULL
		) WITH (autovacuum_enabled = false)`)
	f.exec(t, `
		INSERT INTO `+pgx.Identifier{schema, "wal_filler"}.Sanitize()+` (id, payload)
		SELECT g, repeat('x', 1000)
		FROM generate_series(1, 8000) AS g`)

	tableBytes := f.totalRelationSize(t, table)
	shadowBytes := f.totalRelationSize(t, schemachange.ShadowName(schema, table))
	retained := f.slotRetained(t, row.SlotName)
	require.Greater(t, shadowBytes, resumeDiskMargin, "the shadow alone is more than the margin, so the resume needs its discount")
	require.Greater(t, retained, resumeDiskMargin, "the retained WAL alone is more than the margin, so the resume needs its discount")
	require.Less(t, retained, resumedRunCeiling, "the raised ceiling is above the WAL the slot retained")

	// The operator measures what the volume has free now: the rest of the
	// shadow's headroom and the rest of the raised ceiling, and no more.
	required := 2 * tableBytes
	free := required - shadowBytes + resumedRunCeiling - retained + resumeDiskMargin

	held := f.measureHeld(t)
	assert.GreaterOrEqual(t, held.ShadowBytes, shadowBytes, "the shadow is measured from the catalog, and only grows, as autovacuum may add its maps")
	assert.Less(t, held.ShadowBytes, 2*shadowBytes, "the shadow is measured, not the source and the shadow together")
	assert.GreaterOrEqual(t, held.RetainedWALBytes, retained, "the slot's retained WAL is measured from the server, and only grows")

	// A fresh run's preflight discounts nothing and is refused at the
	// figure, carrying the whole requirement.
	_, err = preflight.CheckCopySwap(t.Context(), f.pool, schema, table, preflight.CopySwapEnvironment{
		LogicalDecoding: true, FreeDiskBytes: free, SlotLagCeilingBytes: resumedRunCeiling,
	})
	envErr, ok := errors.AsType[*preflight.CopySwapEnvironmentError](err)
	require.True(t, ok, "a fresh run at the figure is a disk refusal: %v", err)
	assert.Equal(t, preflight.CopySwapCauseDiskHeadroom, envErr.Cause)
	assert.Equal(t, free, envErr.FreeDiskBytes)
	assert.Equal(t, required, envErr.RequiredShadowBytes)
	assert.Equal(t, resumedRunCeiling, envErr.SlotLagCeilingBytes)
	assert.Zero(t, envErr.HeldShadowBytes)
	assert.Zero(t, envErr.HeldWALBytes)

	resume := f.options()
	resume.CopySwap.FreeDiskBytes = free
	resume.CopySwap.SlotLagCeilingBytes = resumedRunCeiling

	restart := resume
	restart.CopySwap.Restart = schema + "." + table
	v, err = migrate.Run(t.Context(), f.pool, st, restart)
	require.NoError(t, err)
	assert.Equal(t, verdict.OutcomeRefused, v.Outcome)
	assert.Equal(t, verdict.Cause(preflight.CopySwapCauseDiskHeadroom), v.Cause, "a run that starts over is checked as a fresh run")
	assert.Equal(t, checkpoint.PhaseCatchingUp, f.inspectRow(t).Phase, "the refused restart discarded nothing")
	assert.GreaterOrEqual(t, f.totalRelationSize(t, schemachange.ShadowName(schema, table)), shadowBytes, "the shadow still stands")

	v, err = migrate.Run(t.Context(), f.pool, st, resume)
	require.NoError(t, err)
	require.Equal(t, verdict.OutcomeExecutedViaCopyAndSwap, v.Outcome, "%s: %s", v.Reason, v.Detail)
	f.assertZeroDiff(t, shape, alter)
}

// exec runs sql on the fixture's pool.
func (f liveFixture) exec(t *testing.T, sql string) {
	t.Helper()
	_, err := f.pool.Exec(t.Context(), sql)
	require.NoError(t, err)
}

// inspectRow reads the table's checkpoint row the way a host would between
// two runs, without the run's lock.
func (f liveFixture) inspectRow(t *testing.T) checkpoint.Checkpoint {
	t.Helper()
	store, err := checkpoint.NewStore(f.pool, checkpoint.Options{})
	require.NoError(t, err)
	cp, err := store.Inspect(t.Context(), f.table.Schema, f.table.Table)
	require.NoError(t, err)
	return cp
}

// totalRelationSize is the server's total size of a table in the
// fixture's schema: heap, indexes, and TOAST.
func (f liveFixture) totalRelationSize(t *testing.T, table string) int64 {
	t.Helper()
	var size int64
	require.NoError(t, f.pool.QueryRow(t.Context(), `
		SELECT pg_total_relation_size($1::regclass)`,
		pgx.Identifier{f.table.Schema, table}.Sanitize()).Scan(&size))
	return size
}

// slotRetained is the WAL the named slot retains, from its restart
// position to the server's write position.
func (f liveFixture) slotRetained(t *testing.T, slot string) int64 {
	t.Helper()
	var retained int64
	require.NoError(t, f.pool.QueryRow(t.Context(), `
		SELECT pg_wal_lsn_diff(pg_current_wal_lsn(), restart_lsn)::bigint
		FROM pg_replication_slots
		WHERE slot_name = $1`, slot).Scan(&retained))
	return retained
}

// measureHeld is what the route's preflight measures a stopped run on the
// fixture's table to hold, through the same proofs the route takes.
func (f liveFixture) measureHeld(t *testing.T) preflight.CopySwapHeld {
	t.Helper()
	shape, store := f.measureInputs(t)
	held, err := schemachange.MeasureResumeHeld(t.Context(), f.pool, store, shape, true)
	require.NoError(t, err)
	return held
}

// measureInputs is the shape proof and the checkpoint store the route's
// preflight hands MeasureResumeHeld for the fixture's table.
func (f liveFixture) measureInputs(t *testing.T) (preflight.CopySwapShape, *checkpoint.Store) {
	t.Helper()
	role, err := preflight.CheckPrivileges(t.Context(), f.pool, f.table.Schema, f.table.Table,
		preflight.Requirement{Tier: preflight.TierCopyAndSwap, LogicalDecoding: true})
	require.NoError(t, err)
	shape, err := preflight.CheckCopySwapShape(t.Context(), f.pool, f.table.Schema, f.table.Table, role)
	require.NoError(t, err)
	store, err := checkpoint.NewStore(f.pool, checkpoint.Options{})
	require.NoError(t, err)
	return shape, store
}

// A shadow dropped while the resume's preflight measures it counts as
// nothing held. The size read waits on the lock of the transaction that
// drops the shadow, as it would on a restart of the same table discarding
// the stopped run, and then finds no relation: the same answer as no
// shadow at all, not a failed preflight. The slot is untouched, so its
// retained WAL is still counted.
func TestMeasureResumeHeldCountsAShadowDroppedMidReadAsNothingHeld(t *testing.T) {
	f := newLiveFixture(t, testutil.WorkloadShape{})
	st := parseOne(t, fmt.Sprintf(`ALTER TABLE %s ALTER COLUMN amount TYPE numeric(14,4)`, f.table.Qualified()))
	stopped := f.options()
	stopped.CopySwap.OnCheckpoint = func(_ context.Context, cp checkpoint.Checkpoint) error {
		if cp.Phase == checkpoint.PhaseCatchingUp {
			return errStopAtCatchUp
		}
		return nil
	}
	_, err := migrate.Run(t.Context(), f.pool, st, stopped)
	require.ErrorIs(t, err, errStopAtCatchUp)
	shape, store := f.measureInputs(t)

	drop, err := f.pool.Begin(t.Context())
	require.NoError(t, err)
	t.Cleanup(func() { releaseLeftover(t, drop) })
	_, err = drop.Exec(t.Context(), `DROP TABLE `+f.shadowName())
	require.NoError(t, err)

	type measured struct {
		held preflight.CopySwapHeld
		err  error
	}
	done := make(chan measured, 1)
	var wg sync.WaitGroup
	t.Cleanup(wg.Wait)
	wg.Go(func() {
		held, err := schemachange.MeasureResumeHeld(t.Context(), f.pool, store, shape, true)
		done <- measured{held: held, err: err}
	})
	pollUntil(t, f.shadowSizeReadWaitsOnALock, "the shadow's size read waiting on the drop's lock")
	require.NoError(t, drop.Commit(t.Context()))

	m := <-done
	require.NoError(t, m.err, "a shadow that vanished mid-read counts as nothing held")
	assert.Zero(t, m.held.ShadowBytes)
	assert.Positive(t, m.held.RetainedWALBytes, "the stopped run's slot still retains the copy's WAL")
}

// shadowSizeReadWaitsOnALock reports whether a session's shadow size read
// is waiting on a lock.
func (f liveFixture) shadowSizeReadWaitsOnALock(ctx context.Context) (bool, error) {
	var waiting bool
	err := f.pool.QueryRow(ctx, `
		SELECT count(*) > 0
		FROM pg_catalog.pg_stat_activity
		WHERE datname = current_database()
		  AND wait_event_type = 'Lock'
		  AND position('pg_total_relation_size' IN query) > 0
		  AND pid <> pg_backend_pid()`).Scan(&waiting)
	if err != nil {
		return false, fmt.Errorf("find the waiting shadow size read: %w", err)
	}
	return waiting, nil
}
