// Package schemadiff builds the canonical table model both front-ends share
// and diffs two models into an ordered statement list. The model always
// comes from a real PostgreSQL catalog — the live table is introspected
// directly, and a desired-state file is executed on a transaction-scoped
// scratch schema and introspected the same way, then the transaction is
// rolled back (execute-and-introspect; semantics are never derived from the
// AST). Canonical text (types, defaults, constraint and index definitions)
// is whatever the server's own decompilers print, so cosmetic differences
// (type aliases, default formatting, implicit names) never show up as diffs.
//
// This is a periphery package (see SAFETY.md): its output is a plan request,
// and the core executors re-verify their own preconditions.
package schemadiff

import "math"

// Identity is a column's identity kind, as pg_attribute.attidentity spells
// it.
type Identity string

// The identity kinds.
const (
	// IdentityNone means the column is not an identity column.
	IdentityNone Identity = ""
	// IdentityAlways is GENERATED ALWAYS AS IDENTITY.
	IdentityAlways Identity = "a"
	// IdentityByDefault is GENERATED BY DEFAULT AS IDENTITY.
	IdentityByDefault Identity = "d"
)

// Column is one column of the canonical model.
type Column struct {
	// Name is the column name.
	Name string
	// Type is the canonical type text (format_type), e.g. "character
	// varying(50)" — never an alias like varchar(50).
	Type string
	// NotNull reports the NOT NULL attribute.
	NotNull bool
	// Default is the canonical default expression (pg_get_expr), empty when
	// none. For a generated column it is the generation expression.
	Default string
	// SequenceDefault reports that the default expression depends on a
	// sequence (per pg_depend) — a serial column or a hand-written nextval
	// default. In a desired-state model that sequence exists only inside
	// the rolled-back scratch transaction, so no derived plan can
	// reference it.
	SequenceDefault bool
	// SequenceOwned reports that the sequence behind the default is owned
	// by this exact column (a pg_depend OWNED BY edge, deptype 'a') — what
	// the serial shorthand produces. It is false for a hand-written
	// nextval default on a standalone sequence or another table's
	// sequence, however the sequence is named: sharing distinguishes it
	// from ownership, not naming.
	SequenceOwned bool
	// Collation is the column's explicit collation as a schema-qualified,
	// quote_ident-quoted name, empty when the column uses its type's
	// default collation. The declarative model does not manage collations yet, so
	// the model carries it only to refuse: dropping a COLLATE clause from
	// a rendered baseline would silently change sort order and index
	// semantics, and a collation delta cannot be converged without a
	// table rewrite.
	Collation string
	// Identity is the identity kind, IdentityNone for plain columns.
	Identity Identity
	// Generated reports GENERATED ALWAYS AS (...) STORED.
	Generated bool
	// Virtual reports GENERATED ALWAYS AS (...) VIRTUAL, which exists from
	// PostgreSQL 18. The desired-file grammar predates it, so only a live
	// table carries one, and the model records it only to refuse: export
	// cannot write it back and a diff cannot converge it. Omitted from JSON
	// when false, so a model without virtual columns digests the same as it
	// did before the field existed.
	Virtual bool `json:",omitempty"`
	// Sequence is the declaration of the sequence the column owns, an
	// identity's or a serial's, when it differs from what declaring the
	// column fresh would create; nil when it does not, or when the column
	// owns no sequence. Omitted from JSON when nil, so a model whose
	// sequences are all declared at their defaults digests the same as it
	// did before the field existed.
	Sequence *SequenceOptions `json:",omitempty"`
}

// SequenceOptions are the declared parameters of a column-owned sequence
// (pg_sequence). The counter's position is not among them: it is data,
// not schema.
type SequenceOptions struct {
	// Type is the sequence's data type (format_type), e.g. "bigint".
	Type string
	// Start is START WITH.
	Start int64
	// Increment is INCREMENT BY.
	Increment int64
	// Min is MINVALUE.
	Min int64
	// Max is MAXVALUE.
	Max int64
	// Cache is CACHE.
	Cache int64
	// Cycle reports CYCLE.
	Cycle bool
}

// defaultSequenceOptions returns what declaring a column of the given
// integer type as an identity or serial creates: an ascending sequence of
// the column's type from 1 to the type's maximum, uncached, not cycling.
// The second result is false for a type no sequence can back.
func defaultSequenceOptions(columnType string) (SequenceOptions, bool) {
	maxValue, ok := map[string]int64{
		"smallint": math.MaxInt16,
		"integer":  math.MaxInt32,
		"bigint":   math.MaxInt64,
	}[columnType]
	if !ok {
		return SequenceOptions{}, false
	}
	return SequenceOptions{Type: columnType, Start: 1, Increment: 1, Min: 1, Max: maxValue, Cache: 1}, true
}

// declaredSequence returns the options worth recording for a column-owned
// sequence: nil when they are exactly what declaring the column fresh
// creates, so the model records only a declaration a file would have to
// state.
func declaredSequence(columnType string, opts SequenceOptions) *SequenceOptions {
	if def, ok := defaultSequenceOptions(columnType); ok && def == opts {
		return nil
	}
	return &opts
}

// IsGenerated reports a generated column of either kind: its Default is the
// generation expression, never a column default.
func (c Column) IsGenerated() bool {
	return c.Generated || c.Virtual
}

// Constraint is one table constraint: its name plus the server-decompiled
// definition (pg_get_constraintdef), e.g. "PRIMARY KEY (id)".
type Constraint struct {
	// Name is the constraint name.
	Name string
	// Def is the canonical definition text.
	Def string
	// ForeignKey reports a FOREIGN KEY constraint (contype 'f'). Omitted
	// from JSON when false, so a model without foreign keys digests the
	// same as it did before the field existed.
	ForeignKey bool `json:",omitempty"`
}

// Index is one non-constraint index: its name plus the server-decompiled
// CREATE INDEX statement (pg_get_indexdef), unqualified under the
// introspection search_path, and whether the entry is usable.
type Index struct {
	// Name is the index name.
	Name string
	// Def is the canonical CREATE INDEX statement.
	Def string
	// Invalid reports pg_index.indisvalid = false: the entry carries the
	// name and the definition but the planner never uses it, so it does not
	// deliver the desired index. On a plain table it is a concurrent build
	// that has not finished — abandoned, or still running. On a partitioned
	// parent it means not every partition has a matching attached index;
	// the server never builds a partitioned index concurrently. A
	// desired-side index, materialized on the scratch schema, is never
	// invalid, so the zero value is the delivered state.
	Invalid bool
}

// Model is the canonical, comparison-ready description of one table. It
// carries no schema qualification: the live and desired sides are
// introspected under matching search_path settings so their definitions
// compare textually.
type Model struct {
	// Table is the unqualified table name.
	Table string
	// RowSecurity records settings and policies for inspection and export
	// refusal. Diff leaves access control separately managed; absence in a
	// table-only desired file is not a request to remove live policies.
	RowSecurity RowSecurity
	// PartitionKey is the server-decompiled partition key definition
	// (pg_get_partkeydef), e.g. "RANGE (created_at)" — empty for a
	// non-partitioned table.
	PartitionKey string
	// IsPartition reports that the table is itself a partition of a
	// partitioned parent (pg_class.relispartition).
	IsPartition bool
	// InheritsParents lists the classic-inheritance parents of this table.
	// Declarative partitions use the same pg_inherits catalog but are
	// excluded using pg_class.relispartition.
	InheritsParents []string
	// InheritanceChildren lists the classic-inheritance children of this
	// table. The model carries both directions so rendering either side can
	// fail closed rather than flattening inherited columns or losing edges.
	InheritanceChildren []string
	// Unlogged reports that the table is unlogged
	// (pg_class.relpersistence 'u'). The declarative model does not manage
	// persistence yet — converging it (SET LOGGED / SET UNLOGGED) is a
	// full table rewrite — so the model carries it only to refuse:
	// rendering an unlogged table as a plain CREATE TABLE would silently
	// change its crash-safety and replication behavior, and a persistence
	// mismatch fails the diff closed instead of diffing to silence.
	Unlogged bool
	// Options are the table's storage parameters (pg_class.reloptions),
	// with its TOAST table's parameters prefixed "toast.", each as the
	// server stores it ("fillfactor=70"), sorted so the order a file lists
	// them in carries no meaning. A desired file declares them with
	// CREATE TABLE ... WITH (...), and the renderer writes them back the
	// same way. The diff does not converge them, so a mismatch fails
	// closed instead of diffing to silence: a parameter declared in the
	// file but never applied, or a tuned live parameter the file drops,
	// would otherwise plan as no change. Omitted from JSON when empty, so a
	// model without storage parameters digests the same as it did before
	// the field existed.
	Options []string `json:",omitempty"`
	// ToastMayNotRebuild reports that the table has a dropped column and no
	// remaining column that guarantees a TOAST table, so a fresh CREATE
	// TABLE of its columns might build none. The server builds a TOAST
	// table at CREATE TABLE only when the columns need one and silently
	// discards toast.* parameters otherwise. A dropped column is the one
	// change that can leave a TOAST table the remaining columns do not
	// need: adding or retyping a column builds one when the columns come
	// to need it, and a rewrite builds it afresh. A remaining column of an
	// unbounded variable-length type, stored other than PLAIN, settles it,
	// since the server always builds a TOAST table for one. When Options
	// carries TOAST parameters the renderer refuses such a table rather
	// than write a
	// baseline that would plan the parameters again on every diff. Read
	// only alongside TOAST parameters, and not part of the table's shape,
	// so it never reaches a digest.
	ToastMayNotRebuild bool `json:"-"`
	// ReferencedBy lists the incoming foreign keys — constraints on other
	// tables that reference this one — as "table.constraint" strings, in
	// that order. Incoming foreign keys are not part of this table's own
	// definition and cannot be expressed in a desired file, so the model
	// carries them only for the renderer to refuse on.
	ReferencedBy []string
	// Columns are the table's columns in attribute order.
	Columns []Column
	// Constraints are the table constraints, name-sorted.
	Constraints []Constraint
	// Indexes are the non-constraint indexes, name-sorted.
	Indexes []Index
}
