// Rendered SQL is the product artifact a pull produces, so its exact text
// is a legitimate unit-test surface (unlike log output).
func TestRenderGolden(t *testing.T) {
	m := base()
	m.Columns = append(m.Columns,
		Column{Name: "created_at", Type: "timestamp with time zone", NotNull: true, Default: "now()"},
		Column{Name: "doubled", Type: "integer", Generated: true, Default: "(id * 2)"},
		Column{Name: "seq", Type: "bigint", NotNull: true, Identity: IdentityByDefault},
		Column{Name: "note", Type: "text"},
	)
	m.Constraints = append(m.Constraints, Constraint{Name: "name_len", Def: "CHECK ((length((name)::text) > 0))"})

	out, err := Render(m)
	require.NoError(t, err)
	assert.Equal(t, `CREATE TABLE "events" (
    "id" bigint NOT NULL,
    "name" character varying(50) NOT NULL,
    "created_at" timestamp with time zone DEFAULT now() NOT NULL,
    "doubled" integer GENERATED ALWAYS AS ((id * 2)) STORED,
    "seq" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "note" text,
    CONSTRAINT "events_pkey" PRIMARY KEY (id),
    CONSTRAINT "name_len" CHECK ((length((name)::text) > 0))
);

CREATE INDEX events_name_idx ON events USING btree (name);
`, out)
}

// A serial column renders back to its pseudo-type so the desired file
// recreates the owned sequence on the scratch schema. All three
// integer-family mappings are exercised so a typo in any one map entry
// fails a test rather than shipping a wrong pseudo-type.
func TestRenderSerialColumn(t *testing.T) {
	tests := []struct {
		colType string
		want    string
	}{
		{"smallint", "smallserial"},
		{"integer", "serial"},
		{"bigint", "bigserial"},
	}
	for _, tt := range tests {
		t.Run(tt.colType, func(t *testing.T) {
			m := base()
			m.Columns[0] = Column{
				Name: "id", Type: tt.colType, NotNull: true,
				Default: "nextval('events_id_seq'::regclass)", SequenceDefault: true, SequenceOwned: true,
			}

			out, err := Render(m)
			require.NoError(t, err)
			assert.Contains(t, out, `"id" `+tt.want+` NOT NULL`)
		})
	}
}

// Sequence-backed defaults that are not the canonical serial form fail
// closed: a rendered file could never recreate the sequence they reference.
func TestRenderRefusesUnrenderableSequenceDefaults(t *testing.T) {
	tests := []struct {
		name string
		col  Column
	}{
		{"shared sequence", Column{
			Name: "id", Type: "bigint", NotNull: true,
			Default: "nextval('global_id_seq'::regclass)", SequenceDefault: true,
		}},
		{"standalone sequence with the serial-style name", Column{
			Name: "id", Type: "bigint", NotNull: true,
			Default: "nextval('events_id_seq'::regclass)", SequenceDefault: true, SequenceOwned: false,
		}},
		{"owned sequence with a non-serial name", Column{
			Name: "id", Type: "bigint", NotNull: true,
			Default: "nextval('renamed_seq'::regclass)", SequenceDefault: true, SequenceOwned: true,
		}},
		{"nullable serial", Column{
			Name: "id", Type: "bigint",
			Default: "nextval('events_id_seq'::regclass)", SequenceDefault: true, SequenceOwned: true,
		}},
		{"non-integer type", Column{
			Name: "id", Type: "numeric", NotNull: true,
			Default: "nextval('events_id_seq'::regclass)", SequenceDefault: true, SequenceOwned: true,
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			m := base()
			m.Columns[0] = tt.col
			_, err := Render(m)
			require.ErrorIs(t, err, ErrUnrenderableDefault)
		})
	}
}

// Partitioned parents and partitions refuse to render: the model carries no
// partition bounds or topology, so a rendered file would be a silently
// wrong baseline.
func TestRenderRefusesPartitionedTables(t *testing.T) {
	parent := base()
	parent.PartitionKey = "RANGE (id)"
	_, err := Render(parent)
	require.ErrorIs(t, err, ErrUnrenderablePartition)

	child := base()
	child.IsPartition = true
	_, err = Render(child)
	require.ErrorIs(t, err, ErrUnrenderablePartition)
}

func TestRenderRefusesClassicInheritance(t *testing.T) {
	child := base()
	child.InheritsParents = []string{"public.parent"}
	_, err := Render(child)
	require.ErrorIs(t, err, ErrUnrenderableInheritance)

	parent := base()
	parent.InheritanceChildren = []string{"public.child"}
	_, err = Render(parent)
	require.ErrorIs(t, err, ErrUnrenderableInheritance)
}

// A zero-column table is legal PostgreSQL and renders as an empty body,
// not an empty line between the parentheses.
func TestRenderZeroColumnTable(t *testing.T) {
	m := Model{Table: "nocols"}
	out, err := Render(m)
	require.NoError(t, err)
	assert.Equal(t, "CREATE TABLE \"nocols\" ();\n", out)
}

