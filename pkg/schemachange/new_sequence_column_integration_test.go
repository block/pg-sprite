// Adding an identity column beside a retype gives the shadow a sequence the
// source does not have. The swap carries only the source's sequences to the
// live table, so the build refuses the statement inside its own transaction
// and commits nothing. The source's own serial key (id) is not a new
// sequence and does not trip the check.
func TestBuildShadowRefusesANewIdentityColumnBesideARetype(t *testing.T) {
	f := newShadowFixture(t)
	f.createOrders(t)

	_, err := f.build(t, "orders", `
		ALTER TABLE %s.orders
			ADD COLUMN seqno bigint GENERATED BY DEFAULT AS IDENTITY,
			ALTER COLUMN qty TYPE bigint`)

	assert.ErrorIs(t, err, schemachange.ErrInvariantViolation)
	assert.Equal(t, schemachange.CauseStatementNewSequence, schemachange.RefusalCauseOf(err))
	assert.False(t, f.relationExists(t, schemachange.ShadowName(f.schema, "orders")), "a refused build creates nothing")
}

// A serial column is a plain column that owns a sequence created for it, so
