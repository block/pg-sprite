// A statement that only retypes beside the source's own serial key builds:
// the shadow's id still draws from the source's sequence rather than owning
// one, so the check sees no new sequence.
func TestBuildShadowAdmitsARetypeBesideTheSourcesSerialKey(t *testing.T) {
	f := newShadowFixture(t)
	f.createOrders(t)

	built, err := f.build(t, "orders", `
		ALTER TABLE %s.orders
			ALTER COLUMN qty TYPE bigint`)
	require.NoError(t, err)

	assert.Equal(t, []string{"id", "qty", "note", "sku"}, built.CopyColumns())
}

// A source identity column dropped and re-added as an identity is both a
// re-add the copy cannot fill and a new sequence. The re-add check runs
// first and names the more specific cause: the remedy is to split the drop
// and the add, not to attach a sequence later.
func TestBuildShadowRefusesReplacingAnIdentityColumnWithAnIdentityAsAReadd(t *testing.T) {
	f := newShadowFixture(t)
	f.exec(t, `
		CREATE TABLE %s.widgets (
			id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			seqno bigint GENERATED BY DEFAULT AS IDENTITY,
			qty   integer NOT NULL
		)`)

	_, err := f.build(t, "widgets", `
		ALTER TABLE %s.widgets
			DROP COLUMN seqno,
			ADD COLUMN seqno bigint GENERATED BY DEFAULT AS IDENTITY,
			ALTER COLUMN qty TYPE bigint`)

	assert.ErrorIs(t, err, schemachange.ErrInvariantViolation)
	assert.Equal(t, schemachange.CauseStatementReadd, schemachange.RefusalCauseOf(err))
	assert.False(t, f.relationExists(t, schemachange.ShadowName(f.schema, "widgets")), "a refused build creates nothing")
}

// A kept source identity column whose handed-off default the statement
// drops and replaces with an identity of its own mints a sequence on the
// shadow. The new-sequence check runs before the handoff check, so the
// statement is refused as a capability boundary to re-plan, not as a
// handoff the shadow lost.
func TestBuildShadowRefusesAKeptIdentityColumnDeclaredAgainAsANewSequence(t *testing.T) {
	f := newShadowFixture(t)
	f.exec(t, `
		CREATE TABLE %s.widgets (
			id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
			qty integer NOT NULL
		)`)

	_, err := f.build(t, "widgets", `
		ALTER TABLE %s.widgets
			ALTER COLUMN id DROP DEFAULT,
			ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY,
			ALTER COLUMN qty TYPE bigint`)

	assert.ErrorIs(t, err, schemachange.ErrInvariantViolation)
	assert.Equal(t, schemachange.CauseStatementNewSequence, schemachange.RefusalCauseOf(err))
	assert.False(t, f.relationExists(t, schemachange.ShadowName(f.schema, "widgets")), "a refused build creates nothing")
}

// A shadow that owns a sequence the source lacks is refused on inspection
// too, so a resume of such a shadow stops before the copy rather than
// running to the swap. The build cannot leave one, so the test makes it by
// editing a built shadow directly.
func TestInspectShadowRefusesAShadowThatOwnsASequenceTheSourceLacks(t *testing.T) {
	f := newShadowFixture(t)
	f.createOrders(t)
	lock := f.lock(t, "orders")
	target := f.prove(t, "orders")
	alter := f.alter(t, `ALTER TABLE %s.orders ALTER COLUMN qty TYPE bigint`)
	_, err := schemachange.BuildShadow(t.Context(), f.pool, lock, target, alter, schemachange.Options{})
	require.NoError(t, err)
	f.exec(t, `ALTER TABLE %s.`+schemachange.ShadowName(f.schema, "orders")+` ADD COLUMN seqno serial`)

	_, err = schemachange.InspectShadow(t.Context(), f.pool, lock, target, alter, schemachange.Options{})

	assert.ErrorIs(t, err, schemachange.ErrInvariantViolation)
	assert.Equal(t, schemachange.CauseStatementNewSequence, schemachange.RefusalCauseOf(err))
}

// Through the Runner the refusal lands before the run has touched anything:
// the shadow build is the first write, and it rolled back, so there is no
// shadow, no write fence on the source, and no checkpoint row to abandon.
func TestRunnerRefusesANewIdentityColumnBeforeAnyRowOrFence(t *testing.T) {
	f := newRunnerFixture(t)
	f.createOrders(t)

	_, err := f.run(t, "orders", `
		ALTER TABLE %s.orders
			ADD COLUMN seqno bigint GENERATED BY DEFAULT AS IDENTITY,
			ALTER COLUMN qty TYPE bigint`, schemachange.RunOptions{})

	assert.ErrorIs(t, err, schemachange.ErrInvariantViolation)
	assert.Equal(t, schemachange.CauseStatementNewSequence, schemachange.RefusalCauseOf(err))
	assert.False(t, f.relationExists(t, schemachange.ShadowName(f.schema, "orders")), "no shadow was committed")
	assert.False(t, f.hasFence(t, "orders"), "the source was never fenced")
	_, err = f.store.Inspect(t.Context(), f.schema, "orders")
	assert.ErrorIs(t, err, checkpoint.ErrNotFound, "the refused run writes no row")
	f.assertWritable(t, "orders")
}
