// WorkloadTable is the table copy convergence tests run on: one shape,
// with the few variations WorkloadShape allows.
type WorkloadTable struct {
	Schema string
	Table  string
	pool   *pgxpool.Pool
	seed   int64
}

// Qualified returns the safely quoted relation name.
func (w WorkloadTable) Qualified() string { return pgx.Identifier{w.Schema, w.Table}.Sanitize() }

// WorkloadShape is the part of the workload table's shape a test may vary.
// The zero value is the default shape.
type WorkloadShape struct {
	// IDType is the declared type of the identity primary key; empty is
	// bigint. A test that retypes the key itself starts from integer.
	IDType string
}

// NewWorkloadTable creates an empty workload relation in a unique schema.
//
// The shape exercises every convergence race the copy path must survive: an
// identity primary key, a unique secondary key whose values tests swap
// between rows, a numeric column for widening changes, and a text column
// that is always stored out of line so an update leaving it unchanged
// produces a change record with that column omitted. Compression is turned
// off for that column: pglz would otherwise keep a repetitive value inline
// and the omission would never occur.
func NewWorkloadTable(t *testing.T, pool *pgxpool.Pool) WorkloadTable {
	t.Helper()
	return NewWorkloadTableOf(t, pool, WorkloadShape{})
}

// NewWorkloadTableOf is NewWorkloadTable with shape's variations applied.
// Every generator and oracle works over the varied table too: the key is
// still a single identity column, so the load's key moves still draw from
// its sequence.
func NewWorkloadTableOf(t *testing.T, pool *pgxpool.Pool, shape WorkloadShape) WorkloadTable {
	t.Helper()
	idType := shape.IDType
	if idType == "" {
		idType = "bigint"
	}
	schema := NewSchema(t, pool)
	table := "workload"
	qualified := pgx.Identifier{schema, table}.Sanitize()
	q := `CREATE TABLE ` + qualified + ` (
id ` + idType + ` GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uniq integer NOT NULL UNIQUE,
amount numeric(12,2) NOT NULL, label text NOT NULL, blob text,
updated_at timestamptz NOT NULL DEFAULT now())`
	_, err := pool.Exec(t.Context(), q)
	require.NoError(t, err)
	_, err = pool.Exec(t.Context(), `ALTER TABLE `+qualified+` ALTER COLUMN blob SET STORAGE EXTERNAL`)
	require.NoError(t, err)
	return WorkloadTable{Schema: schema, Table: table, pool: pool, seed: 1}
}

// ToastBytes returns the on-disk size of the table's TOAST relation, so a
// test can prove that the blob column really is stored out of line.
func (w WorkloadTable) ToastBytes(ctx context.Context) (int64, error) {
	var size int64
	err := w.pool.QueryRow(ctx, `SELECT coalesce(pg_relation_size(reltoastrelid), 0) FROM pg_class WHERE oid = $1::regclass`, w.Qualified()).Scan(&size)
	if err != nil {
		return 0, fmt.Errorf("toast size of %s: %w", w.Qualified(), err)
	}
	return size, nil
}

// SeedRows inserts n deterministic rows.
func (w WorkloadTable) SeedRows(ctx context.Context, n int) error {
	q := `INSERT INTO ` + w.Qualified() + ` (uniq, amount, label, blob) SELECT g, g::numeric/100, 'row-'||g, repeat(encode(sha256(convert_to(g::text, 'UTF8')), 'hex'), 150) FROM generate_series(1,$1) g`
	_, err := w.pool.Exec(ctx, q, n)
	if err != nil {
		return fmt.Errorf("seed workload table %s: %w", w.Qualified(), err)
	}
	return nil
}

// Mix gives relative weights to workload mutations. KeyMove is an update
// of a row's primary key to a fresh identity value, the change that
// arrives as an image under a new key with a delete under the old one.
type Mix struct {
	Insert     int
	Update     int
	Delete     int
	UniqueMove int
	KeyMove    int
}

// LoadSpec configures a deterministic concurrent workload.
//
// RatePerSecond is the mutation rate of each worker, so the aggregate rate
// is Workers × RatePerSecond. HotRowFraction is the share of updates aimed
// at the ten lowest ids (contention on a hot set); ToastRewriteFraction is
// the share of updates that rewrite the out-of-line blob column — the rest
// leave it unchanged, so their change records omit it.
type LoadSpec struct {
	Seed                 int64
	Workers              int
	RatePerSecond        int
	Mix                  Mix
	HotRowFraction       float64
	ToastRewriteFraction float64
	// RecordFailures keeps the workers running through a mutation that
	// fails for a reason other than an expected race: the failure is
	// recorded in Summary.Failures and the worker takes its next tick. A
	// generator that does not record failures stops every worker on the
	// first one and reports it from Stop. A workload that writes across
	// a swap records failures, because what the swap does to an
	// application's statements is part of what it measures.
	RecordFailures bool
}

// total returns the summed mutation weight.
func (m Mix) total() int { return m.Insert + m.Update + m.Delete + m.UniqueMove + m.KeyMove }

// validate rejects a spec that would start a generator writing nothing or
// picking mutations from an empty mix; a convergence test running against
// such a generator would pass trivially.
func (s LoadSpec) validate() error {
	if s.Workers < 1 {
		return fmt.Errorf("load spec: workers must be at least 1, got %d", s.Workers)
	}
	if s.RatePerSecond < 1 {
		return fmt.Errorf("load spec: rate per second must be at least 1, got %d", s.RatePerSecond)
	}
	if s.Mix.Insert < 0 || s.Mix.Update < 0 || s.Mix.Delete < 0 || s.Mix.UniqueMove < 0 || s.Mix.KeyMove < 0 {
		return fmt.Errorf("load spec: mix weights must not be negative, got %+v", s.Mix)
	}
	if s.Mix.total() < 1 {
		return fmt.Errorf("load spec: mix must have positive total weight, got %+v", s.Mix)
	}
	if s.HotRowFraction < 0 || s.HotRowFraction > 1 {
		return fmt.Errorf("load spec: hot row fraction must be within [0, 1], got %v", s.HotRowFraction)
	}
	if s.ToastRewriteFraction < 0 || s.ToastRewriteFraction > 1 {
		return fmt.Errorf("load spec: toast rewrite fraction must be within [0, 1], got %v", s.ToastRewriteFraction)
	}
	return nil
}

// Summary reports committed operations, inserted and deleted IDs, and the
// number of mutations that aborted on an expected race (a unique-key
// collision, a serialization failure, a deadlock, or a vanished row) and
// were dropped rather than retried. A run whose Races dwarf its committed
// counts wrote far less than its spec suggests.
//
// Touches lists, in commit order, the primary key of every row a committed
// mutation wrote — the inserted, updated, or deleted row, both rows of a
// unique-key swap, and both the old and the new key of a key move — each
// with the WAL position the mutation read while it wrote. A test that
// marks the length of the list at some instant knows that every key before
// the mark committed before it, and can leave the rows written after it
// out of a comparison.
//
// Ambiguous lists the keys of every mutation whose client-side deadline
// expired after it had sent its write: the server may have committed the
// write all the same, before or after the deadline fired, so the row's
// state is unknown and a comparison leaves the key out rather than judge
// it. Each mutation names its keys before it writes, so a write whose
// outcome the client never heard still names the rows it may have changed.
//
// MaxLatency is the longest a committed mutation took from its first
// statement to its commit returning. Failures holds every mutation that
// failed for a reason other than an expected race, when the spec records
// them.
type Summary struct {
	Inserts     int
	Updates     int
	Deletes     int
	UniqueMoves int
	KeyMoves    int
	Races       int
	InsertedIDs []int64
	DeletedIDs  []int64
	Touches     []Touch
	Ambiguous   []int64
	MaxLatency  time.Duration
	Failures    []Failure
}

// Touch is one row a committed mutation wrote: its primary key, and the
// server's WAL insert position the mutation read inside its own write
// statement (or, for a multi-statement mutation, inside its transaction
// after its last write). The mutation held its lock on the table when it
// read the position, so a session holding ACCESS EXCLUSIVE on the table
// for a stretch of WAL either saw this write commit before it was granted
// the lock — the position is below anything it reads under the lock — or
// let the write run only after it committed, when the position is above
// its commit.
type Touch struct {
	ID       int64
	Position uint64
}

// TouchedIDs returns the keys of Touches in the same order.
func (s Summary) TouchedIDs() []int64 {
	ids := make([]int64, len(s.Touches))
	for i, touch := range s.Touches {
		ids[i] = touch.ID
	}
	return ids
}

// Failure is one mutation that failed for a reason other than an expected
// race. Code is the server's SQLSTATE, or empty when the failure was not a
// server error (the mutation's client-side deadline, say).
type Failure struct {
	At   time.Time
	Code string
	Err  error
}

// Committed returns how many mutations of every kind committed.
func (s Summary) Committed() int {
	return s.Inserts + s.Updates + s.Deletes + s.UniqueMoves + s.KeyMoves
}

// LoadGenerator owns running workload workers.
type LoadGenerator struct {
	cancel      context.CancelFunc
	done        chan struct{}
	stopTimeout time.Duration
	mu          sync.Mutex
	summary     Summary
	err         error
	stop        sync.Once
}

// stopTimeout bounds how long Stop waits for workers after cancelling them.
const stopTimeout = 5 * time.Second

// StartLoad starts bounded, cancellable workload workers. An invalid spec
// fails the test immediately rather than starting a generator that writes
// nothing.
func StartLoad(t *testing.T, pool *pgxpool.Pool, table WorkloadTable, spec LoadSpec) *LoadGenerator {
	t.Helper()
	require.NoError(t, spec.validate())
	ctx, cancel := context.WithCancel(t.Context())
	g := &LoadGenerator{cancel: cancel, done: make(chan struct{}), stopTimeout: stopTimeout}
	var wg sync.WaitGroup
	for worker := range spec.Workers {
		wg.Go(func() { g.run(ctx, pool, table, spec, worker) })
	}
	go func() { wg.Wait(); close(g.done) }()
	t.Cleanup(func() { _, _ = g.Stop() })
	return g
}

func (g *LoadGenerator) run(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable, spec LoadSpec, worker int) {
	seed := uint64(spec.Seed) + uint64(worker+1)*0x9e3779b97f4a7c15
	rng := rand.New(rand.NewPCG(seed, seed^0xda3e39cb94b95bdb))
	interval := time.Second / time.Duration(spec.RatePerSecond)
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			mutationCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), MutationTimeout)
			started := time.Now()
			err := g.mutate(mutationCtx, pool, table, spec, rng)
			cancel()
			if err == nil {
				g.committed(time.Since(started))
				continue
			}
			if expectedRace(err) {
				g.race()
				continue
			}
			if spec.RecordFailures {
				g.recordFailure(err)
				continue
			}
			g.fail(err)
			g.cancel()
			return
		}
	}
}

// MutationTimeout is the client-side deadline of one mutation; a mutation
// that outlives it fails with context.DeadlineExceeded.
const MutationTimeout = 2 * time.Second

func (g *LoadGenerator) mutate(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable, spec LoadSpec, rng *rand.Rand) error {
	pick := rng.IntN(spec.Mix.total())
	switch {
	case pick < spec.Mix.Insert:
		return g.insert(ctx, pool, table, rng)
	case pick < spec.Mix.Insert+spec.Mix.Update:
		return g.update(ctx, pool, table, spec, rng)
	case pick < spec.Mix.Insert+spec.Mix.Update+spec.Mix.Delete:
		return g.delete(ctx, pool, table)
	case pick < spec.Mix.Insert+spec.Mix.Update+spec.Mix.Delete+spec.Mix.UniqueMove:
		return g.uniqueMove(ctx, pool, table, rng)
	default:
		return g.keyMove(ctx, pool, table)
	}
}

// walPosition is the SQL expression a mutation reads inside its write: the
// server's WAL insert position as a byte offset, the form Touch.Position
// holds.
const walPosition = `(pg_current_wal_insert_lsn() - '0/0'::pg_lsn)::bigint`

// nextIDQuery draws the next key from the table's identity sequence, so an
// insert or a key move knows the key it writes before it writes it.
const nextIDQuery = `SELECT nextval(pg_get_serial_sequence($1, 'id'))`

// insert draws its key from the identity sequence before it writes, so a
// write whose outcome is unknown still names its row.
func (g *LoadGenerator) insert(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable, rng *rand.Rand) error {
	uniq := 1_000_000 + rng.IntN(1_000_000_000)
	var id, position int64
	if err := pool.QueryRow(ctx, nextIDQuery, table.Qualified()).Scan(&id); err != nil {
		return err
	}
	err := pool.QueryRow(ctx, `INSERT INTO `+table.Qualified()+` (id,uniq,amount,label,blob) VALUES ($1,$2,$3,$4,repeat('x',9000)) RETURNING `+walPosition, id, uniq, "1.25", fmt.Sprintf("insert-%d", uniq)).Scan(&position)
	if err != nil {
		g.writeUnheard(err, id)
		return err
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Inserts++
	g.summary.InsertedIDs = append(g.summary.InsertedIDs, id)
	g.summary.Touches = append(g.summary.Touches, Touch{ID: id, Position: uint64(position)})
	return nil
}

// randomPointQuery picks a uniformly random point in the table's key range
// through the primary key index's two ends; it yields no row on an empty
// table.
func randomPointQuery(table WorkloadTable) string {
	return `SELECT min(id) + floor(random() * (max(id) - min(id) + 1))::bigint FROM ` + table.Qualified()
}

// randomIDQuery picks the first key at or after a random point in the key
// range, so a pick costs two index probes however many rows the table
// holds. Rows that follow a gap in the key space are picked more often
// than their neighbours; the load does not need uniformity, only a cheap
// pick that reaches every part of the table.
func randomIDQuery(table WorkloadTable) string {
	return `SELECT id FROM ` + table.Qualified() + ` WHERE id >= (` + randomPointQuery(table) + `) ORDER BY id LIMIT 1`
}
func (g *LoadGenerator) update(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable, spec LoadSpec, rng *rand.Rand) error {
	var id int64
	idQuery := randomIDQuery(table)
	if rng.Float64() < spec.HotRowFraction {
		idQuery = `SELECT id FROM ` + table.Qualified() + ` ORDER BY id LIMIT 1 OFFSET ` + fmt.Sprint(rng.IntN(10))
	}
	if err := pool.QueryRow(ctx, idQuery).Scan(&id); err != nil {
		return err
	}
	rewrite := rng.Float64() < spec.ToastRewriteFraction
	q := `UPDATE ` + table.Qualified() + ` SET amount=amount+1, label=label||'u', updated_at=now()`
	if rewrite {
		q += `, blob=repeat(encode(sha256(convert_to(random()::text, 'UTF8')), 'hex'), 150)`
	}
	q += ` WHERE id=$1 RETURNING ` + walPosition
	var position int64
	err := pool.QueryRow(ctx, q, id).Scan(&position)
	if errors.Is(err, pgx.ErrNoRows) {
		// The picked row was deleted before the update reached it; the
		// update wrote nothing.
		return nil
	}
	if err != nil {
		g.writeUnheard(err, id)
		return err
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Updates++
	g.summary.Touches = append(g.summary.Touches, Touch{ID: id, Position: uint64(position)})
	return nil
}

// delete picks its row before it writes, so a write whose outcome is
// unknown still names its row; a row deleted between the pick and the
// write is the vanished-row race.
func (g *LoadGenerator) delete(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable) error {
	var id, position int64
	if err := pool.QueryRow(ctx, randomIDQuery(table)).Scan(&id); err != nil {
		return err
	}
	err := pool.QueryRow(ctx, `DELETE FROM `+table.Qualified()+` WHERE id=$1 RETURNING `+walPosition, id).Scan(&position)
	if err != nil {
		g.writeUnheard(err, id)
		return err
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Deletes++
	g.summary.DeletedIDs = append(g.summary.DeletedIDs, id)
	g.summary.Touches = append(g.summary.Touches, Touch{ID: id, Position: uint64(position)})
	return nil
}

// uniqueMove swaps the unique keys of two rows inside one transaction by
// parking the first row on a temporary out-of-range value. Replayed
// statement by statement this is the ordering that trips a naive applier on
// the unique index.
func (g *LoadGenerator) uniqueMove(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable, rng *rand.Rand) error {
	tx, err := pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(ctx)) }()
	rows, err := tx.Query(ctx, `SELECT id,uniq FROM `+table.Qualified()+` WHERE id >= (`+randomPointQuery(table)+`) ORDER BY id LIMIT 2 FOR UPDATE`)
	if err != nil {
		return err
	}
	type pair struct {
		ID   int64
		Uniq int
	}
	values, err := pgx.CollectRows(rows, pgx.RowToStructByPos[pair])
	if err != nil {
		return err
	}
	if len(values) < 2 {
		return nil
	}
	temp := -2_000_000_000 + rng.IntN(100_000_000)
	for _, args := range [][]any{{temp, values[0].ID}, {values[0].Uniq, values[1].ID}, {values[1].Uniq, values[0].ID}} {
		if _, err = tx.Exec(ctx, `UPDATE `+table.Qualified()+` SET uniq=$1,updated_at=now() WHERE id=$2`, args...); err != nil {
			return err
		}
	}
	var position int64
	if err = tx.QueryRow(ctx, `SELECT `+walPosition).Scan(&position); err != nil {
		return err
	}
	// Only the commit can land a write the client never hears about: a
	// statement before it that runs out the deadline leaves the
	// transaction uncommitted.
	if err = tx.Commit(ctx); err != nil {
		g.writeUnheard(err, values[0].ID, values[1].ID)
		return err
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.UniqueMoves++
	g.summary.Touches = append(g.summary.Touches,
		Touch{ID: values[0].ID, Position: uint64(position)},
		Touch{ID: values[1].ID, Position: uint64(position)})
	return nil
}

// keyMove gives a random row a fresh primary key from the table's identity
// sequence, so the change decodes as an image under the new key carrying
// the old key: the two halves the buffer pairs and the drain judges
// together. It picks the row and draws the new key before it writes, so a
// write whose outcome is unknown still names both keys. A worker whose
// chosen row vanished under it sees the vanished-row race.
func (g *LoadGenerator) keyMove(ctx context.Context, pool *pgxpool.Pool, table WorkloadTable) error {
	var oldID, newID, position int64
	if err := pool.QueryRow(ctx, randomIDQuery(table)).Scan(&oldID); err != nil {
		return err
	}
	if err := pool.QueryRow(ctx, nextIDQuery, table.Qualified()).Scan(&newID); err != nil {
		return err
	}
	err := pool.QueryRow(ctx, `UPDATE `+table.Qualified()+` SET id=$2, updated_at=now() WHERE id=$1 RETURNING `+walPosition, oldID, newID).Scan(&position)
	if err != nil {
		g.writeUnheard(err, oldID, newID)
		return err
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.KeyMoves++
	g.summary.Touches = append(g.summary.Touches,
		Touch{ID: oldID, Position: uint64(position)},
		Touch{ID: newID, Position: uint64(position)})
	return nil
}

// writeUnheard records the keys of a write whose outcome the client never
// heard: one that ran out its client-side deadline after it was sent, which
// the server may still have committed. A server error is an answer, after
// which the write has rolled back, so it is not listed; nor is a dropped
// connection, which the load reports as a failure of its own.
func (g *LoadGenerator) writeUnheard(err error, ids ...int64) {
	if !errors.Is(err, context.DeadlineExceeded) {
		return
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Ambiguous = append(g.summary.Ambiguous, ids...)
}
func expectedRace(err error) bool {
	if errors.Is(err, pgx.ErrNoRows) || errors.Is(err, context.Canceled) {
		return true
	}
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && (pgErr.Code == "23505" || pgErr.Code == "40001" || pgErr.Code == "40P01")
}
func (g *LoadGenerator) race() {
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Races++
}
func (g *LoadGenerator) committed(latency time.Duration) {
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.MaxLatency = max(g.summary.MaxLatency, latency)
}
func (g *LoadGenerator) recordFailure(err error) {
	failure := Failure{At: time.Now(), Err: err}
	if pgErr, ok := errors.AsType[*pgconn.PgError](err); ok {
		failure.Code = pgErr.Code
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	g.summary.Failures = append(g.summary.Failures, failure)
}
func (g *LoadGenerator) fail(err error) {
	g.mu.Lock()
	defer g.mu.Unlock()
	if g.err == nil {
		g.err = err
	}
}

// Snapshot returns the summary accumulated so far and leaves the workers
// running, so a test can mark how much the load had committed when it
// observed some point in the run under test.
func (g *LoadGenerator) Snapshot() Summary {
	g.mu.Lock()
	defer g.mu.Unlock()
	s := g.summary
	s.InsertedIDs = slices.Clone(s.InsertedIDs)
	s.DeletedIDs = slices.Clone(s.DeletedIDs)
	s.Touches = slices.Clone(s.Touches)
	s.Ambiguous = slices.Clone(s.Ambiguous)
	s.Failures = slices.Clone(s.Failures)
	return s
}

// Progress is how much a load has committed so far, without the key and
// failure histories a Summary carries, so a poll that needs only the counts
// costs the same however long the load has run.
type Progress struct {
	Inserts     int
	Updates     int
	Deletes     int
	UniqueMoves int
	KeyMoves    int
	// Touched is how long Summary.Touches was: the first Touched entries of
	// the final list are the rows written by mutations that committed
	// before this progress was read.
	Touched int
}

// Committed returns how many mutations of every kind committed.
func (p Progress) Committed() int {
	return p.Inserts + p.Updates + p.Deletes + p.UniqueMoves + p.KeyMoves
}

// Progress returns the counts accumulated so far and leaves the workers
// running, under one acquisition of the lock the workers record under.
func (g *LoadGenerator) Progress() Progress {
	g.mu.Lock()
	defer g.mu.Unlock()
	s := &g.summary
	return Progress{
		Inserts:     s.Inserts,
		Updates:     s.Updates,
		Deletes:     s.Deletes,
		UniqueMoves: s.UniqueMoves,
		KeyMoves:    s.KeyMoves,
		Touched:     len(s.Touches),
	}
}

// Stop promptly cancels workers and waits a bounded time for completion. It
// always returns the summary accumulated so far; when workers do not stop in
// time the error joins the deadline with any worker error already recorded,
// so a wedged worker's cause is not lost behind the timeout.
func (g *LoadGenerator) Stop() (Summary, error) {
	g.stop.Do(g.cancel)
	deadline := time.NewTimer(g.stopTimeout)
	defer deadline.Stop()
	var stopErr error
	select {
	case <-g.done:
	case <-deadline.C:
		stopErr = fmt.Errorf("stop load generator: workers still running after %s", g.stopTimeout)
	}
	g.mu.Lock()
	defer g.mu.Unlock()
	return g.summary, errors.Join(g.err, stopErr)
}
