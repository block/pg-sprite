-- Baseline schema and data for the demo tour. Rerunnable: drops and
-- recreates everything, so every `make demo` starts from the same state.
-- Identity (not serial) keys so the declarative diff never meets a
-- sequence-backed default it must refuse.
--
-- The tables live in public, named explicitly: the compose role shares its
-- name with the engine's own schema, which a copy-and-swap run creates for
-- its checkpoint table, and from then on an unqualified CREATE TABLE under
-- the role's default search_path would land there instead.
SET search_path = public;
DROP TABLE IF EXISTS users, orders, widgets CASCADE;

CREATE TABLE users (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email  text,
    name   varchar(50),
    status text DEFAULT 'active'
);

-- Enough rows that constraint validation and index builds do visible work,
-- small enough to stay instant. Every email is non-null so the SET NOT NULL
-- tour step's VALIDATE passes.
INSERT INTO users (email, name)
SELECT 'u' || g || '@example.com', 'user ' || g
FROM generate_series(1, 10000) g;

CREATE TABLE orders (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer,
    total   numeric(10,2),
    note    text
);

INSERT INTO orders (user_id, total, note)
SELECT (g % 10000) + 1, g, 'order ' || g
FROM generate_series(1, 5000) g;

-- One note wider than the varchar(32) the exec tour's data-fault step
-- narrows the column to. It sits past the copier's first chunks, so the
-- fault is met after rows have already landed in the shadow and the
-- abandon has something to discard. Every other note stays well inside
-- the width, so the later widening to varchar(200) copies cleanly.
UPDATE orders SET note = repeat('x', 64) WHERE id = 4000;

-- An index the exec tour drops with the plain (blocking) DROP INDEX under
-- the --accept-blocking acknowledgement. It lives on orders, which no
-- desired-state file describes, so the diff tour's plans do not see it.
CREATE INDEX orders_total_idx ON orders (total);

-- Dedicated fixture for atomic desired-state row security.
CREATE SCHEMA IF NOT EXISTS demo_security;
DROP TABLE IF EXISTS demo_security.demo_rls;
CREATE TABLE demo_security.demo_rls (
    id bigint PRIMARY KEY,
    owner_id bigint NOT NULL
);
